// packages/web/dist → src/assets.gen.ts: every file imported `with { type: "file" }` (bun build --compile embeds them)
// and a path → content-type map; without a built UI a one-page placeholder
import { readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import { join, relative, extname } from "node:path";
const dist = join(import.meta.dir, "..", "..", "web", "dist");
const out = join(import.meta.dir, "..", "src", "assets.gen.ts");
const TYPES: Record<string, string> = { ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8", ".woff2": "font/woff2", ".svg": "image/svg+xml", ".png": "image/png", ".ico": "image/x-icon", ".json": "application/json", ".txt": "text/plain; charset=utf-8" };
// .vite (the build manifest, for the size check) is not served
function walk(d: string): string[] { const o: string[] = []; for (const f of readdirSync(d)) { if (f === ".vite") continue; const p = join(d, f); if (statSync(p).isDirectory()) o.push(...walk(p)); else o.push(p); } return o; }
const lines = ["// generated by scripts/embed.ts — do not edit", "// @ts-nocheck: Bun file imports (with { type: \"file\" }) are not modelled by TypeScript", 'import type { Asset } from "./http.ts";'];
const entries: string[] = [];
if (existsSync(dist)) {
  walk(dist).sort().forEach((f, i) => {
    const rel = "/" + relative(dist, f).split("\\").join("/");
    lines.push("import f" + i + " from " + JSON.stringify(relative(join(import.meta.dir, "..", "src"), f)) + ' with { type: "file" };');
    entries.push("  [" + JSON.stringify(rel) + ", { file: f" + i + ", type: " + JSON.stringify(TYPES[extname(f)] ?? "application/octet-stream") + " }],");
  });
} else entries.push('  ["/index.html", { file: new Blob(["<!doctype html><title>agentglass</title><p>The web UI is not built: pnpm --filter @agentglass/web build</p>"]), type: "text/html; charset=utf-8" }],');
lines.push("export const ASSETS = new Map<string, Asset>([", ...entries, "]);");
writeFileSync(out, lines.join("\n") + "\n");
console.log("wrote " + out + " (" + entries.length + " files)");
