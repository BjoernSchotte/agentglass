// schema/*.json → src/types.gen.ts (json-schema-to-typescript); --check fails when the committed file is stale
import { compile } from "json-schema-to-typescript";
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const dir = join(import.meta.dir, "..", "schema");
const out = join(import.meta.dir, "..", "src", "types.gen.ts");
const names = readdirSync(dir).filter((f) => f.endsWith(".json")).sort();
const schemas = new Map(names.map((f) => [JSON.parse(readFileSync(join(dir, f), "utf8")).$id as string, JSON.parse(readFileSync(join(dir, f), "utf8"))]));
// $ref by $id: resolved from this folder
const resolver = { order: 1, canRead: true, read: (f: { url: string }) => { const id = f.url.split("/").pop() ?? ""; const s = schemas.get(id); if (!s) throw new Error("unknown $ref " + f.url); return s; } };
const parts = ["// generated by scripts/gen.ts from schema/*.json — do not edit; pnpm --filter @agentglass/api-contract gen\n"];
// each schema declares its own type once; a $ref names the referenced schema's type (declared by its own file)
for (const [id, s] of schemas) parts.push((await compile(s, id, { bannerComment: "", $refOptions: { resolve: { file: false, http: false, schema: resolver } } as never, additionalProperties: true, declareExternallyReferenced: false, format: true })).trim() + "\n");
const text = parts.join("\n");
if (process.argv.includes("--check")) {
  if (!existsSync(out) || readFileSync(out, "utf8") !== text) { console.error("types.gen.ts is stale: run pnpm --filter @agentglass/api-contract gen"); process.exit(1); }
  console.log("types.gen.ts is fresh");
} else { writeFileSync(out, text); console.log("wrote " + out); }
